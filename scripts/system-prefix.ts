/**
 * Generates src/system-prefix.generated.ts from the pinned OMP SDK.
 *
 * - systemPrefix: OMP's bundled system-prompt template rendered up to the line
 *   before its first `{{` expression, trailing whitespace trimmed. This is the
 *   same slice the qualified 8.1 tree used (wt `system-prompt.ts:638-645`). No
 *   setting, path, date, model, tool or context file reaches it.
 * - sideChannelReminder: the verbatim developer message stock OMP adds to every
 *   ephemeral side-turn snapshot (`agent-session.ts` #buildEphemeralSnapshot).
 *   omp-noli uses it to keep side turns out of main-loop registration.
 *
 * Digests and lengths cover UTF-8 bytes. `--check` fails when the file is stale.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { render } from "@oh-my-pi/pi-utils/prompt";

const root = join(import.meta.dir, "..");
const sdk = join(root, "node_modules/@oh-my-pi/pi-coding-agent");
const version: unknown = JSON.parse(readFileSync(join(sdk, "package.json"), "utf8")).version;
if (typeof version !== "string" || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error("Pinned OMP SDK has no release version");

const digest = (text: string) => {
	const bytes = Buffer.from(text, "utf8");
	return { sha256: createHash("sha256").update(bytes).digest("hex"), len: bytes.length };
};

const template = readFileSync(join(sdk, "src/prompts/system/system-prompt.md"), "utf8");
const end = template.lastIndexOf("\n", template.indexOf("{{"));
if (template.indexOf("{{") < 0 || end <= 0) throw new Error("OMP system prompt template has no static prefix");
const prefix = render(template.slice(0, end)).trimEnd();
if (!prefix) throw new Error("OMP system prompt static prefix rendered empty");
const reminder = readFileSync(join(sdk, "src/prompts/system/side-channel-no-tools.md"), "utf8");
if (!reminder) throw new Error("OMP side-channel reminder is empty");

const text = `// Generated by scripts/system-prefix.ts from @oh-my-pi/pi-coding-agent ${version}. Do not edit.
export interface TextDigest { sha256: string; len: number }
/** Bundled system-prompt static prefix per OMP version (UTF-8). */
export const SYSTEM_PREFIXES: Readonly<Record<string, TextDigest>> = ${JSON.stringify({ [version]: digest(prefix) })};
/** Stock ephemeral side-turn reminder per OMP version (UTF-8). */
export const SIDE_CHANNEL_REMINDERS: Readonly<Record<string, TextDigest>> = ${JSON.stringify({ [version]: digest(reminder) })};
`;
const output = join(root, "src/system-prefix.generated.ts");
if (process.argv.includes("--check")) {
	if (readFileSync(output, "utf8") !== text) throw new Error("src/system-prefix.generated.ts is stale; run bun scripts/system-prefix.ts");
} else writeFileSync(output, text);
